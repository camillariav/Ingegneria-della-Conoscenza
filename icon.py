def numero_prolog(value):
    """Converte un valore numerico in una rappresentazione valida per Prolog."""
    value = float(value)
    if not np.isfinite(value):
        raise ValueError(f"Valore numerico non valido per Prolog: {value}")
    return repr(value)

def inferisci_patogeni(row):
    """Restituisce tutti i patogeni dedotti dalla KB per una riga del dataset."""
    crop = str(row['label']).strip().lower()
    temp = numero_prolog(row['temperature'])
    umidita = numero_prolog(row['humidity'])
    pioggia = numero_prolog(row['rainfall'])
    n = numero_prolog(row['N'])
    p = numero_prolog(row['P'])
    k = numero_prolog(row['K'])
    ph = numero_prolog(row['ph'])

    query = (
        f"rischio_patogeno('{crop}', {temp}, {umidita}, {pioggia}, "
        f"{n}, {p}, {k}, {ph}, Patogeno)"
    )

    risultati = list(prolog.query(query))
    patogeni = sorted({str(risultato['Patogeno']) for risultato in risultati})
    return patogeni

