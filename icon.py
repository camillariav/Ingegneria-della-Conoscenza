# Learning curves.

def plot_learning_curve(estimator, title, X_data, y_data, cv):
    """Disegna le curve di apprendimento usando F1 binario."""
    sizes, train_scores, valid_scores = learning_curve(estimator, X_data, y_data, cv=cv, scoring='f1', n_jobs=-1, train_sizes=np.linspace(0.1, 1.0, 5), shuffle=True, random_state=RANDOM_STATE, error_score='raise')

    train_mean = np.mean(train_scores, axis=1)
    train_std = np.std(train_scores, axis=1)
    valid_mean = np.mean(valid_scores, axis=1)
    valid_std = np.std(valid_scores, axis=1)

    train_lower = np.clip(train_mean - train_std, 0, 1)
    train_upper = np.clip(train_mean + train_std, 0, 1)
    valid_lower = np.clip(valid_mean - valid_std, 0, 1)
    valid_upper = np.clip(valid_mean + valid_std, 0, 1)

    plt.figure(figsize=(8, 6))
    plt.title(title)
    plt.xlabel('Numero di esempi di training')
    plt.ylabel('F1-score')
    plt.grid(True, linestyle='--', alpha=0.6)
    plt.fill_between(sizes, train_lower, train_upper, alpha=0.15)
    plt.fill_between(sizes, valid_lower, valid_upper, alpha=0.15)
    plt.plot(sizes, train_mean, 'o-', label='Training score')
    plt.plot(sizes, valid_mean, 'o-', label='Cross-validation score')
    plt.ylim(0, 1)
    plt.legend(loc='best')
    plt.tight_layout()
    plt.show()

cv_curve = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)
